"""WotLK 3.3.5a SRP6 client primitives for an authorized, loopback-only lab.

Protocol arithmetic follows AzerothCore's Authentication/SRP6.cpp. It is not
hardened cryptography (Python ints/strings cannot be reliably wiped) and must
NOT be used for production account login or a public credential collection UI.
No original game client or game assets are needed.
"""
from __future__ import annotations

import hashlib
import hmac
import secrets
from dataclasses import dataclass

from .azerothcore_auth_probe import ProbeError

# AzerothCore stores SRP integers little-endian. The canonical hexadecimal
# modulus in upstream SRP6.cpp is big-endian; its wire representation is not.
MODULUS = int("894B645E89E1535BBDAD5B8B290650530801B18EBFBF5E8FAB3C82872A3E9BB7", 16)
N_BYTES = MODULUS.to_bytes(32, "little")
GENERATOR = 7
K_MULTIPLIER = 3


def sha1(*parts: bytes) -> bytes:
    digest = hashlib.sha1()
    for part in parts:
        digest.update(part)
    return digest.digest()


def le(value: int, size: int = 32) -> bytes:
    return value.to_bytes(size, "little")


def validate_identity(username: str, password: str) -> tuple[str, str]:
    if not isinstance(username, str) or not 1 <= len(username) <= 16 or not username.isascii() or not username.isalnum():
        raise ProbeError("Local test account must be 1-16 ASCII letters/digits")
    if not isinstance(password, str) or not 1 <= len(password) <= 64 or not password.isascii():
        raise ProbeError("Local test password must be 1-64 ASCII characters")
    return username.upper(), password.upper()  # AzerothCore legacy account normalization


def session_key_interleave(secret: bytes) -> bytes:
    """Same 40-byte SHA1 interleave as AzerothCore's SHA1Interleave(S)."""
    if len(secret) != 32:
        raise ProbeError("Invalid SRP6 shared secret size")
    # In AzerothCore, leading zero bytes are skipped in aligned pairs.
    start = next((i for i, value in enumerate(secret) if value), len(secret))
    if start % 2:
        start += 1
    offset = start // 2
    a = sha1(secret[0::2][offset:])
    b = sha1(secret[1::2][offset:])
    result = bytearray(40)
    result[0::2], result[1::2] = a, b
    return bytes(result)


@dataclass(frozen=True)
class ServerChallenge:
    B: bytes
    salt: bytes
    security_flags: int
    version_challenge: bytes


def parse_server_challenge(packet: bytes) -> ServerChallenge:
    """Accept only AzerothCore's 3.3.5a standard, no-PIN/matrix/TOTP challenge."""
    if len(packet) < 3 or packet[0:2] != b"\x00\x00":
        raise ProbeError("Unexpected logon challenge header")
    if packet[2] != 0:
        raise ProbeError(f"Authentication challenge rejected (code {packet[2]})")
    # 3-byte result prefix + B32 + g_len + g1 + N_len + N32 + salt32 + challenge16 + flags1
    if len(packet) != 119:
        raise ProbeError("Unrecognized 3.3.5a challenge length or security extension")
    B = packet[3:35]
    generator_length = packet[35]
    generator = packet[36]
    modulus_length = packet[37]
    modulus = packet[38:70]
    salt = packet[70:102]
    random_bytes = packet[102:118]
    flags = packet[118]
    if generator_length != 1 or generator != GENERATOR or modulus_length != 32 or modulus != N_BYTES:
        raise ProbeError("Unsupported SRP6 group parameters")
    if not 0 < int.from_bytes(B, "little") % MODULUS < MODULUS:
        raise ProbeError("Invalid server SRP6 public key")
    if flags:
        raise ProbeError("PIN, matrix, and TOTP auth are not supported by the lab")
    return ServerChallenge(B, salt, flags, random_bytes)


@dataclass(frozen=True)
class ClientProof:
    packet: bytes
    expected_M2: bytes
    # Secret session key is kept inside this object only for a future world
    # protocol boundary; never serialize or print it.
    session_key: bytes


def create_client_proof(username: str, password: str, challenge: ServerChallenge,
                        *, secret_a: bytes | None = None) -> ClientProof:
    username, password = validate_identity(username, password)
    if len(challenge.B) != 32 or len(challenge.salt) != 32 or challenge.security_flags != 0:
        raise ProbeError("Malformed server SRP6 challenge")
    B = int.from_bytes(challenge.B, "little")
    if not 0 < B % MODULUS < MODULUS:
        raise ProbeError("Invalid server public key")
    # Generated by OS CSPRNG by default; injection is reserved for offline tests.
    if secret_a is None:
        secret_a = secrets.token_bytes(32)
    if not isinstance(secret_a, bytes) or len(secret_a) != 32:
        raise ProbeError("Expected 32-byte ephemeral secret")
    a = int.from_bytes(secret_a, "little")
    if a == 0:
        raise ProbeError("Invalid ephemeral secret")
    A = le(pow(GENERATOR, a, MODULUS))
    identity_hash = sha1(f"{username}:{password}".encode("ascii"))
    x = int.from_bytes(sha1(challenge.salt, identity_hash), "little")
    u = int.from_bytes(sha1(A, challenge.B), "little")
    if u == 0:
        raise ProbeError("Invalid SRP6 scrambling parameter")
    base = (B - K_MULTIPLIER * pow(GENERATOR, x, MODULUS)) % MODULUS
    if base == 0:
        raise ProbeError("Invalid SRP6 client base")
    S = le(pow(base, a + u * x, MODULUS))
    K = session_key_interleave(S)
    group_xor = bytes(left ^ right for left, right in zip(sha1(N_BYTES), sha1(bytes((GENERATOR,)))))
    M1 = sha1(group_xor, sha1(username.encode("ascii")), challenge.salt, A, challenge.B, K)
    M2 = sha1(A, M1, K)
    proof_packet = b"\x01" + A + M1 + (b"\x00" * 20) + b"\x00\x00"
    assert len(proof_packet) == 75
    return ClientProof(proof_packet, M2, K)


def verify_server_proof(response: bytes, expected_M2: bytes) -> None:
    if len(response) < 2 or response[0] != 0x01:
        raise ProbeError("Unexpected server proof header")
    if response[1] != 0:
        raise ProbeError(f"Logon proof rejected (code {response[1]})")
    if len(response) != 32 or len(expected_M2) != 20:
        raise ProbeError("Malformed successful 3.3.5a server proof")
    if not hmac.compare_digest(response[2:22], expected_M2):
        raise ProbeError("Server proof M2 mismatch; session is not authenticated")
